// ---------- backend SQLite (node:sqlite, tanpa dependensi) ----------
function createSQLiteBackend() {
  const { DatabaseSync } = require("node:sqlite");
  const dataDir = path.join(__dirname, "..", "data");
  fs.mkdirSync(dataDir, { recursive: true });
  const dbFile = process.env.SQLITE_FILE || path.join(dataDir, "warung.db");
  const raw = new DatabaseSync(dbFile);
  raw.exec("PRAGMA journal_mode = WAL;");
  raw.exec("PRAGMA foreign_keys = ON;");

  const stmtCache = new Map();
  function prep(sql) {
    let s = stmtCache.get(sql);
    if (!s) {
      s = raw.prepare(sql); // ? dipakai apa adanya di SQLite
      stmtCache.set(sql, s);
    }
    return s;
  }

  const api = {
    backend: "sqlite",
    dbFile,
    initSchema: async () => { raw.exec(ddl(SCHEMA_SQL, false)); },
    prepare: (sql) => ({
      get: async (...params) => prep(sql).get(...argsList(params)),
      all: async (...params) => prep(sql).all(...argsList(params)),
      run: async (...params) => {
        const r = prep(sql).run(...argsList(params));
        return { changes: Number(r.changes), lastInsertRowid: r.lastInsertRowid };
      },
    }),
    exec: async (sql) => { raw.exec(sql); },
    tx: async (fn) => {
      raw.exec("BEGIN");
      try {
        const out = await fn(api); // SQLite satu koneksi: tx memakai API yang sama
        raw.exec("COMMIT");
        return out;
      } catch (err) {
        try { raw.exec("ROLLBACK"); } catch {}
        throw err;
      }
    },
  };
  return api;
}

// ---------- backend PostgreSQL (Neon) ----------
function createPgBackend() {
  const { Pool, types } = require("pg");
  types.setTypeParser(20, (v) => (v === null ? null : parseInt(v, 10))); // int8 -> Number
  types.setTypeParser(1700, (v) => (v === null ? null : parseFloat(v))); // numeric -> Number

  const pool = new Pool({
    connectionString: DATABASE_URL,
    // Neon wajib TLS; ?sslmode=require di URL juga cukup.
    ssl: /sslmode=(require|allow|prefer|verify-ca|verify-full)/.test(DATABASE_URL)
      ? { rejectUnauthorized: false }
      : undefined,
  });

  function bind(sql) {
    return toPgPlaceholders(sql);
  }

  const api = {
    backend: "postgres",
    pool,
    initSchema: async () => { await pool.query(ddl(SCHEMA_SQL, true)); },
    prepare: (sql) => {
      const qs = bind(sql);
      return {
        get: async (...params) => (await pool.query(qs, argsList(params))).rows[0],
        all: async (...params) => (await pool.query(qs, argsList(params))).rows,
        run: async (...params) => {
          const r = await pool.query(qs, argsList(params));
          return { changes: r.rowCount, lastInsertRowid: null };
        },
      };
    },
    exec: async (sql) => { await pool.query(sql); },
    tx: async (fn) => {
      const client = await pool.connect();
      try {
        await client.query("BEGIN");
        const t = {
          prepare: (s) => {
            const qs = bind(s);
            return {
              get: async (...p) => (await client.query(qs, argsList(p))).rows[0],
              all: async (...p) => (await client.query(qs, argsList(p))).rows,
              run: async (...p) => {
                const r = await client.query(qs, argsList(p));
                return { changes: r.rowCount, lastInsertRowid: null };
              },
            };
          },
        };
        const out = await fn(t);
        await client.query("COMMIT");
        return out;
      } catch (err) {
        try { await client.query("ROLLBACK"); } catch {}
        throw err;
      } finally {
        client.release();
      }
    },
  };
  return api;
}

// ---------- konfigurasi ongkir ----------
// Sumber angka yang tampil di aplikasi adalah tabel `areas` (dikelola admin).
// Nilai konstan di bawah hanya cadangan bila tabel areas masih kosong.
const ONGKIR = Number(process.env.ONGKIR || 5000);
const ONGKIR_GRATIS_MIN = Number(process.env.ONGKIR_GRATIS_MIN || 50000);

/** Wilayah by id. Mengembalikan null bila tidak ada. */
async function getArea(id) {
  if (id === undefined || id === null || id === "") return null;
  return await db.prepare("SELECT * FROM areas WHERE id = ?").get(parseInt(id, 10));
}

/** Wilayah pertama (urutan terkecil) — cadangan bila profil belum punya pilihan. */
async function getDefaultArea() {
  return (
    (await db.prepare("SELECT * FROM areas WHERE aktif = 1 ORDER BY urutan ASC, id ASC").get()) || null
  );
}

/** Ongkir berdasarkan wilayah (fallback konstan bila tidak ada wilayah). */
function hitungOngkirArea(area, subtotal) {
  if (!area) return ONGKIR;
  const gratisMin = Number(area.gratis_min) || 0;
  if (gratisMin > 0 && subtotal >= gratisMin) return 0;
  return Number(area.ongkir) || 0;
}

