/**
 * Lapisan database Warung Mami — bisa jalan di SQLite (lokal) maupun
 * PostgreSQL/Neon (produksi) lewat API async yang sama persis:
 *
 *   const { db } = require("./db");
 *   const row = await db.prepare("SELECT ... WHERE id = ?").get(id);
 *   const rows = await db.prepare("SELECT ...").all();
 *   const info = await db.prepare("UPDATE ...").run(a, b);   // info.changes
 *   const txDb = db.tx((t) => ...);                          // transaksi
 *
 * Aturan main (supaya skrip yang sama valid di dua backend):
 *   - Parameter SELALU pakai tanda tanya `?` (diterjemahkan ke $1, $2 untuk PG).
 *   - INSERT yang butuh id balik: tambahkan `RETURNING id` di SQL (bukan lastInsertRowid).
 *   - Timestamp ditulis sebagai teks "YYYY-MM-DD HH:MM:SS" via localNow()/localToday().
 *   - DDL memakai token {{ID}} dan {{NOW}} yang diterjemahkan per backend.
 *
 * Backend dipilih otomatis:
 *   - Ada env DATABASE_URL (atau di .env) -> PostgreSQL/Neon.
 *   - Tanpa itu                     -> SQLite lokal (data/warung.db).
 */
const fs = require("node:fs");
const path = require("node:path");

// ---------- .env sederhana (tanpa dependensi dotenv) ----------
(function loadEnv() {
  const file = path.join(__dirname, "..", ".env");
  if (!fs.existsSync(file)) return;
  for (const line of fs.readFileSync(file, "utf8").split("\n")) {
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const i = t.indexOf("=");
    if (i < 1) continue;
    const key = t.slice(0, i).trim();
    let val = t.slice(i + 1).trim();
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    if (!(key in process.env)) process.env[key] = val;
  }
})();

// ---------- util waktu (teks lokal, format sama di kedua backend) ----------
function localNow() {
  const d = new Date();
  const p = (n) => String(n).padStart(2, "0");
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())} ${p(d.getHours())}:${p(d.getMinutes())}:${p(d.getSeconds())}`;
}
function localToday() {
  return localNow().slice(0, 10);
}

// ---------- terjemahan DDL & placeholder ----------
// {{ID}}   -> kolom id utama (auto-increment) per backend
// {{NOW}}  -> DEFAULT waktu sekarang per backend
function ddl(sql, isPG) {
  return sql
    .replace(/\{\{ID\}\}/g, isPG ? "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : "INTEGER PRIMARY KEY AUTOINCREMENT")
    .replace(/\{\{NOW\}\}/g, isPG ? "to_char(localtimestamp, 'YYYY-MM-DD HH24:MI:SS')" : "(datetime('now','localtime'))");
}

// Ganti ? -> $1,$2,... (hanya untuk PG). Lewati string dan komentar.
function toPgPlaceholders(sql) {
  let out = "";
  let n = 0;
  let inStr = false;
  let i = 0;
  while (i < sql.length) {
    const c = sql[i];
    if (inStr) {
      out += c;
      if (c === "'") {
        if (sql[i + 1] === "'") { out += "'"; i += 2; continue; }
        inStr = false;
      }
      i++;
      continue;
    }
    if (c === "'") { inStr = true; out += c; i++; continue; }
    if (c === "-" && sql[i + 1] === "-") {
      const j = sql.indexOf("\n", i);
      if (j === -1) { out += sql.slice(i); break; }
      out += sql.slice(i, j + 1); i = j + 1; continue;
    }
    if (c === "?") { n++; out += "$" + n; i++; continue; }
    out += c; i++;
  }
  return out;
}

// Normalisasi daftar argumen: dukung .all(a, b) maupun .all([a, b]).
function argsList(params) {
  if (params.length === 1 && Array.isArray(params[0])) return params[0];
  return params;
}

